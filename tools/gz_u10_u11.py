        '<article class="mat-card" id="gw%d" data-tags="%s%s">'
        '<div class="mat-head"><span class="mid">#%02d</span><h3>%s</h3><span class="msrc">%s</span></div>%s'
        "<p><b>主旨：</b>%s</p>"
