def work_questions(t):
    """一篇古文能出的題目：(題型, 題目, 正解, 錯誤選項)。"""
    title, au, genre, src, line, core = W[t]
    others = [w for w in WORKS if w[0] != t]
    qs = []
    if au:
        era, tag = AUTHORS[au]
        oa = sorted({w[1] for w in others if w[1] and w[1] != au})
        qs.append(("作者", "〈%s〉的作者是誰？" % title, au, oa))
        oe = [e for e in ERAS if e != era and e not in ERA_CLASH.get(era, set())]
        qs.append(("時代", "〈%s〉的作者%s生活在哪個時代？" % (title, au), era, oe))
        ot = sorted({AUTHORS[w[1]][1] for w in others if w[1] and w[1] != au})
        qs.append(("作家特色", "下列敘述，何者是〈%s〉作者%s的特色？" % (title, au), tag, ot))
    cl = GENRE_CLUSTER[genre]
    og = [GENRE_NAME[g] for g in GENRE_NAME if GENRE_CLUSTER[g] != cl]
    qs.append(("文體", "〈%s〉屬於哪一類文體？" % title, GENRE_NAME[genre], og))
    if src:
        os_ = sorted({w[3] for w in others if w[3] and w[3] != src and w[3].split("・")[0] != src.split("・")[0]})
        qs.append(("出處", "〈%s〉選自哪一部書？" % title, src, os_))
    if line:
        ol = ["〈%s〉" % w[0] for w in others]
        qs.append(("名句", "「%s」出自哪一篇？" % line, "〈%s〉" % title, ol))
    return qs


def facts_row(t):
    title, au, genre, src, line, core = W[t]
    who = "%s（%s）" % (au, AUTHORS[au][0]) if au else "—"
    return ["〈%s〉%s" % (title, "<span class=\"core\">核心</span>" if core else ""), who, GENRE_NAME[genre].split("（")[0], src or "—", "「%s」" % line if line else "—"]


def build_schedule():
    """排出 60 天，每天 5 題。第 1–49 天依週主題（每週 6 天新題＋1 天複習），第 50–60 天綜合複習。"""
    rng = random.Random(116)
    days, asked = [], []
    for wk, theme, works in WEEKS:
        cons = [("concept", c) for c in CONCEPTS if c[0] == wk]
        # 每篇的題目打散後輪流排，讓每天碰到不同篇目
        per = {t: [("work", (t,) + q) for q in work_questions(t)] for t in works}
        for t in per:
            rng.shuffle(per[t])
        stream = []
        while any(per.values()):
            for t in works:
                if per[t]:
                    stream.append(per[t].pop())
        week_new = []
        for d in range(6):
            items = stream[d * 3:(d + 1) * 3]
            if d < len(cons):
                items.append(cons[d])
            extra = stream[18 + d] if 18 + d < len(stream) else (rng.choice(asked) if asked else stream[d])
            items.append(extra)
            items = items[:5]
            while len(items) < 5:
                items.append(rng.choice(stream))
            dw = []
            for k, x in items:
                if k == "work" and x[0] in works and x[0] not in dw:
                    dw.append(x[0])
            days.append((wk, theme, sorted(dw, key=works.index), items))
            week_new += items
        rev = rng.sample([i for i in week_new if i[0] == "work"], 4) + [rng.choice(cons)]
        days.append((wk, theme + "・本週複習", list(works), rev))
        asked += week_new
    allwq = [("work", (t,) + q) for t in W for q in work_questions(t)]
    allc = [("concept", c) for c in CONCEPTS]
    focus = [("作家辨識", ["作家特色", "作者"]), ("時代先後", ["時代"]), ("文體判斷", ["文體"]), ("出處", ["出處"]),
             ("名句", ["名句"]), ("核心十五篇", "core"), ("文學常識", "concept"), ("作家特色", ["作家特色"]),
             ("文體與出處", ["文體", "出處"]), ("名句與作者", ["名句", "作者"]), ("考前總複習", "all")]
    for n, (name, f) in enumerate(focus):
        if f == "concept":
            pick = rng.sample(allc, 5)
        elif f == "all":
            pick = rng.sample(allwq, 3) + rng.sample(allc, 2)
        elif f == "core":
            pick = rng.sample([x for x in allwq if W[x[1][0]][5]], 5)
        else:
            pick = rng.sample([x for x in allwq if x[1][1] in f], 4) + [rng.choice(allc)]
        days.append((8 if n < 7 else 9, "綜合複習：" + name, [], pick))
    assert len(days) == 60, len(days)
    return days


def render_item(c, rng, kind, x):
    if kind == "concept":
        _, q, opts, ans, expl = x
        order = list(range(4))
        rng.shuffle(order)
        o = [opts[i] for i in order]
        return mc(c, q, o, "ABCD"[order.index(ans)], expl)
    t, typ, q, a, wrong = x
    ws = rng.sample(wrong, 3)
    o = ws + [a]
    rng.shuffle(o)
    title, au, genre, src, line, core = W[t]
    bits = []
    if au:
        bits.append("作者%s（%s）" % (au, AUTHORS[au][0]))
    bits.append("文體：%s" % GENRE_NAME[genre].split("（")[0])
    if src:
        bits.append("出處：%s" % src)
    if line:
        bits.append("名句「%s」" % line)
    expl = "〈%s〉：%s。" % (title, "，".join(bits))
    if typ == "作家特色":
        expl += "%s的特色是：%s。" % (au, AUTHORS[au][1])
    return mc(c, "<span class=\"qtype\">%s</span>%s" % (typ, q), o, "ABCD"[o.index(a)], expl)


